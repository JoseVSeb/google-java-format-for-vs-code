// Drives the bundled formatter through CheerpJ's library mode.
//
// CheerpJ mounts the origin of the hosting page at /app/, so the jar's virtual path is
// "/app" plus its URL pathname. Everything below runs client side: the jar is fetched by
// CheerpJ, the JVM is WebAssembly, and no Java source ever leaves the page.

const JAR_URL = new URL("../dist/gjf-cheerpj.jar", import.meta.url);
const JAR_PATH = "/app" + JAR_URL.pathname;

const els = {
  status: document.getElementById("status"),
  log: document.getElementById("log"),
  input: document.getElementById("input"),
  output: document.getElementById("output"),
  format: document.getElementById("format"),
  selftest: document.getElementById("selftest"),
  javaVersion: document.getElementById("javaVersion"),
  style: document.getElementById("style"),
  fixImports: document.getElementById("fixImports"),
  formatJavadoc: document.getElementById("formatJavadoc"),
  reorderModifiers: document.getElementById("reorderModifiers"),
};

let formatter = null;
let selfTest = null;

function log(message) {
  els.log.textContent += message + "\n";
}

function status(message, kind = "") {
  els.status.textContent = message;
  els.status.className = "status " + kind;
}

async function boot() {
  if (typeof cheerpjInit !== "function") {
    status("CheerpJ did not load. Check the network tab for cjrtnc.leaningtech.com.", "error");
    return;
  }

  const javaVersion = els.javaVersion.value;
  const started = performance.now();
  try {
    status(`Starting CheerpJ with the Java ${javaVersion} runtime…`);
    await cheerpjInit({ javaVersion, status: "none" });
    log(`cheerpjInit(javaVersion: ${javaVersion}) in ${Math.round(performance.now() - started)} ms`);

    status(`Loading ${JAR_PATH}…`);
    const loaded = performance.now();
    const lib = await cheerpjRunLibrary(JAR_PATH);
    formatter = await lib.gjfweb.api.BrowserFormatter;
    log(`library loaded in ${Math.round(performance.now() - loaded)} ms`);

    const version = await formatter.version();
    status(`Ready — google-java-format ${version} on CheerpJ's Java ${javaVersion} runtime`, "ok");
    els.format.disabled = false;
    els.selftest.disabled = !selfTest;
  } catch (error) {
    status("CheerpJ failed to start: " + error, "error");
    log(String(error && error.stack ? error.stack : error));
  }
}

async function format(source) {
  const json = await formatter.format(
    source,
    els.style.value,
    els.fixImports.checked,
    els.formatJavadoc.checked,
    els.reorderModifiers.checked,
  );
  return JSON.parse(json);
}

els.format.addEventListener("click", async () => {
  els.format.disabled = true;
  const started = performance.now();
  status("Formatting…");
  try {
    const result = await format(els.input.value);
    const elapsed = Math.round(performance.now() - started);
    if (result.ok) {
      els.output.value = result.output;
      status(`Formatted in ${elapsed} ms`, "ok");
    } else {
      els.output.value = "";
      status(result.error, "error");
    }
  } catch (error) {
    status("Formatting threw: " + error, "error");
  } finally {
    els.format.disabled = false;
  }
});

els.selftest.addEventListener("click", async () => {
  els.selftest.disabled = true;
  let failures = 0;
  for (const testCase of selfTest.cases) {
    const result = await format(testCase.input);
    const actual = result.ok ? result.output : "ERROR: " + result.error;
    if (actual === testCase.expected) {
      log(`PASS ${testCase.name}`);
    } else {
      failures++;
      log(`FAIL ${testCase.name}`);
      log("  expected " + JSON.stringify(testCase.expected.slice(0, 120)));
      log("  actual   " + JSON.stringify(actual.slice(0, 120)));
    }
  }
  const total = selfTest.cases.length;
  status(
    failures === 0
      ? `Self-test passed: ${total} file(s) match the reference output byte for byte`
      : `Self-test failed: ${failures} of ${total} file(s) differ, see the log`,
    failures === 0 ? "ok" : "error",
  );
  els.selftest.disabled = false;
});

els.javaVersion.addEventListener("change", () => {
  status("Reload the page to switch the Java runtime.", "error");
});

// The self-test cases are generated by build.sh from the same bundle, formatted by a
// desktop JVM, so a mismatch means CheerpJ's JVM disagreed with a stock one.
try {
  const response = await fetch(new URL("selftest.json", import.meta.url));
  if (response.ok) {
    selfTest = await response.json();
    els.input.value = selfTest.cases[0].input;
    log(`self-test fixtures: ${selfTest.cases.map((c) => c.name).join(", ")}`);
  }
} catch (error) {
  log("no self-test fixtures: " + error);
}

boot();
